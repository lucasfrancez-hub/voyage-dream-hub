import { chamarCompreFacil } from "@/lib/comprefacil/auth.server";
import { supabaseAdmin } from "@/integrations/supabase/client.server";
const OID = 5771972;
const r = await chamarCompreFacil(`/api/Reserva/${OID}/false`);
const o: any = r.dados ?? {};
const a: any = o?.Aereos?.[0] ?? {};
const loc = a?.Localizador ?? a?.LocalizadorAereo ?? "MI497S";
const { data: at } = await supabaseAdmin.from("frt_reservas").select("detalhes").eq("orcamento_id", OID).maybeSingle();
const det: any = { ...((at?.detalhes as any) ?? {}) };
det.passos = (det.passos ?? []).map((p: any) => p.passo === "Reservar aéreo" ? { ...p, ok: true, detalhe: `Localizador ${loc}` } : p);
await supabaseAdmin.from("frt_reservas").upsert({ orcamento_id: OID, localizador_aereo: loc, limite_emissao: a?.DataLimiteEmissao ?? a?.LimiteTempoEmissao ?? "2026-08-25T22:29:09", status: "reservado", detalhes: det }, { onConflict: "orcamento_id" });
console.log("ok", loc);
